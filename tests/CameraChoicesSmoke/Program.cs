using YuiTracking;
using System.Text.Json;
using Item = YuiTracking.CameraChoices.Item;
static void Check(bool ok, string name) { if (!ok) throw new Exception(name); Console.WriteLine("PASS " + name); }
static JsonElement Command(CameraChoices choices, Item item) => JsonSerializer.SerializeToElement(choices.StartCommand(item));
var choices = new CameraChoices();
var usb = new Item("native-usb", "BSW305MBK", true);
var laptop = new Item("native-internal", "Internal Camera", true);
choices.UpdateNative(new[] { usb, laptop });
choices.UpdateBrowser(new[] { new Item("browser-internal", "Internal Camera") });
var list = choices.Build();
Check(list.Count == 3 && list.Contains(usb), "partial named browser list retains native USB camera");
Check(list.Count(item => item.Label == "Internal Camera") == 1, "unique name uses browser device ID without duplicate");
Check(CameraChoices.Select(list, usb) == usb, "native selection survives incomplete browser refresh");
choices.UpdateBrowser(Array.Empty<Item>());
Check(choices.Build().Contains(usb), "empty browser list does not erase native cameras");
choices.UpdateBrowser(new[] { new Item("anonymous", "カメラ 1") });
Check(!choices.Build().Any(item => item.Id == "anonymous"), "anonymous browser device does not replace native names");
choices.UpdateBrowser(new[] { new Item("browser-usb", "BSW305MBK (0411:1234)") });
list = choices.Build();
Check(CameraChoices.Select(list, usb).Id == "browser-usb", "permission refresh preserves selected camera across ID sources");
var direct = Command(choices, CameraChoices.Select(list, usb));
Check(direct.GetProperty("deviceId").GetString() == "browser-usb" && direct.GetProperty("cameraLabel").GetString() == "", "browser choice starts with exact ID");
choices.UpdateBrowser(new[] { new Item("a", "USB Camera"), new Item("b", "USB Camera") });
choices.UpdateNative(new[] { new Item("native-a", "USB Camera", true), new Item("native-b", "USB Camera", true) });
Check(choices.Build().Count(item => item.Label == "USB Camera") == 4, "ambiguous camera names never merge unrelated devices");
var multi = Command(choices, choices.Build().First(item => item.Native));
Check(!multi.GetProperty("singleNativeCamera").GetBoolean(), "multiple native cameras never enable single-device fallback");
choices.UpdateNative(new[] { usb });
choices.UpdateBrowser(Array.Empty<Item>());
var named = Command(choices, usb);
Check(named.GetProperty("cameraLabel").GetString() == "BSW305MBK" && named.GetProperty("deviceId").GetString() == "" && named.GetProperty("singleNativeCamera").GetBoolean(), "native choice resolves its name and single-device mismatch");
choices.UpdateNative(Array.Empty<Item>());
list = choices.Build();
Check(list.Count == 1 && list[0].Id == CameraChoices.DefaultId, "no devices still permits explicit system-default start");
var system = Command(choices, list[0]);
Check(system.GetProperty("deviceId").GetString() == "" && system.GetProperty("cameraLabel").GetString() == "", "system default bypasses device-ID and label matching");
choices.UpdateBrowser(new[] { new Item("browser-only", "USB Camera") });
Check(choices.Build().Any(item => item.Id == "browser-only"), "browser-only camera remains selectable without native device");
choices.UpdateNative(new[] { usb });choices.UpdateBrowser(Array.Empty<Item>());choices.UpdateNative(Array.Empty<Item>());
Check(!choices.Build().Contains(usb), "native unplug removes stale native camera");
choices.UpdateNative(new[] { usb });choices.UpdateBrowser(new[] { new Item("browser-usb", "BSW305MBK") });
list = choices.Build();
Check(CameraChoices.Select(list, new Item(CameraChoices.DefaultId, "システム既定のカメラ")).Id == CameraChoices.DefaultId, "explicit default choice remains selected on refresh");
Check(CameraChoices.Select(list, null).Id == "browser-usb", "initial selection prefers detected physical camera");
